    @Synchronized fun text(value: String): String {
        val key = keys[value] ?: return value
        if (!::context.isInitialized) return value
        val selected = if (language == "system") Locale.getDefault().language else language
        if (selected != cachedLanguage || localized == null) {
            localized = context.createConfigurationContext(Configuration(context.resources.configuration).apply { setLocale(Locale.forLanguageTag(selected)) })
            cachedLanguage = selected
        }
        return localized!!.getString(key)
    }
}
fun l10n(value: String): String = Strings.text(value)

fun l10n(russian: String, english: String): String = if ((if (Strings.language == "system") Locale.getDefault().language else Strings.language) == "ru") russian else english
